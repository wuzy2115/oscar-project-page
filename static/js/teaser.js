// Teaser: single pre-rendered MP4 (2x4 grid, 10s, baked-in captions).
// The build script + manifest live alongside the asset at
// static/videos/teaser/{build_grand.sh, manifest.json, grand.mp4}.

const TAKEAWAYS = [
  { stat: "Trained with 1 GPU", body: "Finetuned from Cosmos-Predict2.5-2B on a single GH200." },
  { stat: "Omni-Embodiment", body: "AgiBot G1, Toyota HSR, Franka, KUKA, MANO &mdash; unified under one model." },
  { stat: "Precise Action Following", body: "Action conditioning yields fine-grained per-joint control." },
];

export function mountTeaser(root) {
  const pillsHtml = TAKEAWAYS.map(
    (k) => `
      <div class="teaser-pill">
        <div class="teaser-pill-stat">${k.stat}</div>
        <div class="teaser-pill-body">${k.body}</div>
      </div>
    `
  ).join("");

  root.innerHTML = `
    <div class="teaser-grand">
      <video src="static/videos/teaser/grand.mp4"
             autoplay muted loop playsinline preload="metadata"
             aria-label="OSCAR generated rollouts across eight embodiments">
    </div>
    <p class="teaser-caption">
      All videos are generated by <strong>OSCAR</strong> from the first frame and robot action
      condition. OSCAR is an action-conditioned video model that generalizes across four robot
      embodiments &mdash; AgiBot G1, Toyota HSR, Franka Panda, KUKA iiwa &mdash; plus the MANO
      human hand.
    </p>
    <div class="teaser-pills">${pillsHtml}</div>
  `;
}
